-- Таблица категорий
CREATE TABLE public.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    CONSTRAINT categories_name_check CHECK (
        char_length(name) BETWEEN 1 AND 100 
        AND name = btrim(name)
    ),
    CONSTRAINT categories_id_check CHECK (id > 0)
);

-- Таблица задач
CREATE TABLE public.tasks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    completed boolean NOT NULL DEFAULT false,
    priority text NOT NULL,
    category_id integer NOT NULL,
    CONSTRAINT tasks_title_check CHECK (
        char_length(title) BETWEEN 1 AND 100 
        AND title = btrim(title)
    ),
    CONSTRAINT tasks_priority_check CHECK (
        priority IN ('low', 'medium', 'high')
    ),
    CONSTRAINT tasks_id_check CHECK (id > 0),
    CONSTRAINT tasks_category_id_fkey FOREIGN KEY (category_id) 
        REFERENCES public.categories(id) ON DELETE RESTRICT
);

-- Индекс для внешнего ключа
CREATE INDEX tasks_category_id_idx ON public.tasks(category_id);